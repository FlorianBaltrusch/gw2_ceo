import pandas as pd

import general_data as gd

CRIT_CHANCE_PRECISION_EQUIV = 21  # 21 precision = 1% critical chance at level 80
BASE_TOUGHNESS = 1000


class Profession:
    """Stat effects of a set of selected traits/skills.

    Rows come from assets/traits.csv (generated by generate_traits.py) and are
    identified by their official GW2 API ids, so a decoded build template
    chat link can be mapped onto them directly.
    """

    def __init__(self, trait_ids: list[int], profession: str | None = None,
                 conditions: set[str] | None = None,
                 stacks: dict[int, int] | None = None,
                 variants: dict[int, list[str]] | None = None,
                 wvw: bool = False):
        table: pd.DataFrame = gd.traits
        rows = table.loc[table["id"].isin(trait_ids)].copy()

        # PvE/WvW-split facts carry their WvW value in value_wvw; the WvW
        # toggle swaps it in (rows without a split keep their value)
        if wvw and "value_wvw" in rows.columns:
            split = rows["value_wvw"].notna()
            rows.loc[split, "value"] = rows.loc[split, "value_wvw"]

        missing = set(trait_ids) - set(rows["id"])
        if missing:
            raise ValueError(f"Unknown trait ids: {sorted(missing)}")

        # rows conditional on a boon (requires "fury"/"might") only count when
        # the corresponding toggle satisfies the condition
        if conditions is None:
            conditions = {"fury", "might"}
        requires = rows["requires"].fillna("")
        rows = rows.loc[(requires == "") | requires.isin(conditions)].copy()

        # stack-scaled rows: value = per_stack x chosen stacks, plus a bonus
        # at full stacks (Empowered Empowerment's jump). Linked rows (the two
        # Catalyst traits) share one stack count via their stack_group.
        stacks = stacks or {}
        scaled = rows.index[rows["max_stacks"].notna()]
        for index in scaled:
            row = rows.loc[index]
            maximum = int(row["max_stacks"])
            default = int(row["default_stacks"]) if pd.notna(row["default_stacks"]) else maximum
            chosen = int(stacks.get(int(row["stack_group"]), default))
            chosen = max(0, min(maximum, chosen))
            value = float(row["per_stack"]) * chosen
            if chosen == maximum and pd.notna(row["max_stack_bonus"]):
                value += float(row["max_stack_bonus"])
            rows.loc[index, "value"] = value

        # variant rows (Elemental Polyphony's attunements): keep only the
        # chosen variants; the data marks the default pair (a Weaver holds at
        # most two distinct attunements, never doubled)
        variant = rows["variant"].fillna("")
        for trait_id in rows.loc[variant != "", "id"].unique():
            of_trait = (rows["id"] == trait_id) & (variant != "")
            default = rows.loc[of_trait & (rows["variant_default"] == 1), "variant"]
            chosen_variants = (variants or {}).get(int(trait_id), list(default))
            rows = rows.loc[~of_trait | rows["variant"].isin(chosen_variants)]

        professions = rows["profession"].unique()
        if len(professions) > 1:
            raise ValueError(f"Traits from multiple professions selected: {list(professions)}")
        if profession and len(professions) and professions[0].lower() != profession.lower():
            raise ValueError(f"Traits belong to {professions[0]}, not {profession}")

        unvalued = rows.loc[rows["value"].isna()]
        if not unvalued.empty:
            raise ValueError(
                f"Trait rows without a reviewed value: {', '.join(unvalued['name'].unique())}"
            )

        self.rows: pd.DataFrame = rows
        self.conversions: pd.DataFrame = rows.loc[rows["source"].notna()]

        precision_conversions = self.conversions.loc[self.conversions["effect"] == "precision"]
        if not (precision_conversions["source"] == "vitality").all():
            raise NotImplementedError(
                "Only vitality-to-precision conversions are supported so far"
            )

    def _flat(self, attribute: str) -> float:
        flat = self.rows.loc[(self.rows["effect"] == attribute) & self.rows["source"].isna()]
        all_stats = self.rows.loc[self.rows["effect"] == "all_stats_flat"]
        return float(flat["value"].sum() + all_stats["value"].sum())

    def additional_power(self):
        return self._flat("power")

    def additional_precision(self):
        return self._flat("precision")

    def additional_ferocity(self):
        return self._flat("ferocity")

    def additional_vitality(self):
        return self._flat("vitality")

    def additional_crit_chance(self):
        """Critical chance bonuses, in precision equivalents."""
        crit = self.rows.loc[self.rows["effect"] == "crit_chance"]
        return float(crit["value"].sum()) * CRIT_CHANCE_PRECISION_EQUIV

    def attribute_multiplier(self):
        """Percentage all-attribute traits (Elemental Empowerment, Fortissimo)
        multiply the final attribute totals - modeled on the hero panel after
        all flat bonuses and conversions; several sources add their
        percentages. Duration and chance percentages are not attributes and
        stay outside the multiplier."""
        rows = self.rows.loc[self.rows["effect"] == "all_stats_pct"]
        return 1 + float(rows["value"].sum()) / 100

    def power_per_might(self):
        """Extra power per stack of might (on top of might's own 30)."""
        per_might = self.rows.loc[self.rows["effect"] == "power_per_might"]
        return float(per_might["value"].sum())

    def vit_prec_conversion(self):
        rows = self.conversions
        vit_prec = rows.loc[(rows["effect"] == "precision") & (rows["source"] == "vitality")]
        return float(vit_prec["value"].sum())

    def stat_conversion(self, vitality, power, precision, ferocity):
        """Apply attribute conversions; all conversions read the pre-conversion
        values (they do not chain). The vitality-to-precision conversion is
        excluded here because calculate.py already accounts for it when
        distributing the armor stats.

        Order of operations beyond that is undocumented in the game: the only
        wiki note (Zealous Blade: its conditional half feeds conversions, the
        base does not) concerns a profession without any conversion trait, so
        modeling every flat bonus as conversion input is consistent with all
        that is actually known."""
        base = {
            "power": power,
            "precision": precision,
            "ferocity": ferocity,
            "vitality": vitality,
            "toughness": BASE_TOUGHNESS + self._flat("toughness"),
        }
        result = {key: base[key] for key in ("vitality", "power", "ferocity")}
        for row in self.conversions.to_dict("records"):
            if row["effect"] in result:
                result[row["effect"]] += base[row["source"]] * row["value"]
        return result["vitality"], result["power"], result["ferocity"]

    # ---------- boon-duration mode ----------

    def additional_concentration(self):
        return self._flat("concentration")

    def additional_healing(self):
        return self._flat("healing")

    def boon_duration_pct(self):
        """Flat percentage boon duration from traits (adds linearly with
        concentration inside the capped term)."""
        rows = self.rows.loc[self.rows["effect"] == "boon_duration_pct"]
        return float(rows["value"].sum())

    def outgoing_heal_pct(self):
        """Outgoing-healing modifiers; they stack additively in GW2."""
        rows = self.rows.loc[self.rows["effect"] == "outgoing_heal_pct"]
        return float(rows["value"].sum())

    def conversion_rates(self, effect: str) -> dict[str, float]:
        """Summed conversion rates into one attribute, keyed by source
        (conversions read pre-conversion values and do not chain)."""
        rows = self.conversions.loc[self.conversions["effect"] == effect]
        rates: dict[str, float] = {}
        for row in rows.to_dict("records"):
            rates[row["source"]] = rates.get(row["source"], 0.0) + row["value"]
        return rates

    def ferocity_equivalent(self, ferocity):
        """crit_damage_pct trait rows are multiplicative on-crit damage
        modifiers, not additions to the ferocity attribute: they scale every
        gear option by the same factor and cannot change the ranking, so they
        are deliberately NOT folded into the ferocity here — doing so would
        distort the power/ferocity trade-off."""
        return ferocity
